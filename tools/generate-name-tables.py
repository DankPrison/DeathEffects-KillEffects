# Particles that take a block or item even though they appeared after 1.8.
LATER_KINDS = {
    "FALLING_DUST": "block",
    "DUST_PILLAR": "block",
    "BLOCK_CRUMBLE": "block",
    "DUST_COLOR_TRANSITION": "dust",
}


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    return re.sub(r"//[^\n]*", "", src)


def enum_body(src, enum_name):
    start = src.index("public enum " + enum_name)
    start = src.index("{", start) + 1
    depth = 0
    i = start
    # The constant list ends at the first ';' at nesting depth 0.
    while i < len(src):
        c = src[i]
        if c in "({[":
            depth += 1
        elif c in ")}]":
            depth -= 1
        elif c == ";" and depth == 0:
            return src[start:i]
        i += 1
    raise ValueError("unterminated enum " + enum_name)


def split_top_level(body):
    parts, depth, cur = [], 0, []
    for c in body:
        if c in "({[":
            depth += 1
        elif c in ")}]":
            depth -= 1
        if c == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(c)
    if "".join(cur).strip():
        parts.append("".join(cur))
    return parts


def parse_constants(body):
    """Yields (name, args, annotations) for each enum constant."""
    for raw in split_top_level(body):
        text = raw.strip()
        if not text:
            continue
        annotations = re.findall(r"@\w+\s*(?:\([^)]*\))?", text)
        text = re.sub(r"@\w+\s*(?:\([^)]*\))?", "", text).strip()
        m = re.match(r"([A-Z0-9_]+)\s*(?:\((.*)\))?\s*$", text, re.S)
        if not m:
            raise ValueError("cannot parse constant: " + raw)
        yield m.group(1), (m.group(2) or ""), annotations


def gen_materials(xs_root, out):
    path = os.path.join(xs_root, "core/src/main/java/com/cryptomorin/xseries/XMaterial.java")
    src = strip_comments(open(path, encoding="utf-8").read())
    rows = []
    for name, args, _ in parse_constants(enum_body(src, "XMaterial")):
        data = "0"
        cond = re.match(r"\s*supports\(1,\s*(\d+)\)\s*\?\s*(\d+)\s*:\s*0\s*,", args)
        if cond:
            data = "%s@1.%s" % (cond.group(2), cond.group(1))
        else:
            num = re.match(r"\s*(\d+)\s*(,|$)", args)
            if num:
                data = num.group(1)
        legacy = re.findall(r'"([A-Z0-9_]+)"', args)
        rows.append(" ".join([name, data] + legacy))
    with open(out, "w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("# MODERN_NAME DATA LEGACY_NAMES...\n")
        f.write("# DATA is the pre-1.13 data value; 'N@1.12' means it only applies from 1.12 on.\n")
        f.write("\n".join(rows) + "\n")
    return len(rows)


def gen_sounds(xs_root, out):
    path = os.path.join(xs_root, "core/src/main/java/com/cryptomorin/xseries/XSound.java")
    src = strip_comments(open(path, encoding="utf-8").read())
    rows = []
    seen = set()
    for m in re.finditer(r"\b([A-Z0-9_]+)\s*=\s*std\(([^)]*)\)", src):
        name = m.group(1)
        if name in seen:
            continue
        seen.add(name)
        names = re.findall(r'"([^"]+)"', m.group(2))
        key = next((n for n in names if "." in n or n.islower()), "-")
        legacy = [n for n in names if n != key and n != name]
        rows.append(" ".join([name, key] + legacy))
    with open(out, "w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("# CANONICAL_NAME KEY LEGACY_NAMES...\n")
        f.write("\n".join(rows) + "\n")
    return len(rows)


def gen_particles(xs_root, out):
    path = os.path.join(xs_root, "core/src/main/java/com/cryptomorin/xseries/particles/XParticle.java")
    src = strip_comments(open(path, encoding="utf-8").read())
    rows = {}
    order = []
    legacy_by_canonical = {row[0]: row for row in LEGACY_PARTICLES}
    for name, args, annotations in parse_constants(enum_body(src, "XParticle")):
        literals = [s for s in re.findall(r'"([A-Z0-9_]+)"', args)]
        merged = []
        for a in annotations:
            mm = re.search(r'XMerge\s*\(.*name\s*=\s*"([A-Z0-9_]+)"', a)
            if mm:
                merged.append(mm.group(1))
        if name in legacy_by_canonical:
            continue
        removed = any("removedSince" in a for a in annotations)
        old = literals[0] if literals else name
        kind = LATER_KINDS.get(name, "plain")
        rows[name] = (name, "-" if removed else name, old, "-", "-", kind, merged)
        order.append(name)
    lines = []
    for row in LEGACY_PARTICLES:
        lines.append(" ".join(row))
    for name in order:
        canonical, modern, old, nms18, n17, kind, merged = rows[name]
        line = " ".join([canonical, modern, old, nms18, n17, kind])
        if merged:
            line += " " + " ".join(merged)
        lines.append(line)
    with open(out, "w", encoding="utf-8") as f:
        f.write(HEADER)
        f.write("# CANONICAL NAME_1.20.5+ NAME_1.9-1.20.4 NAME_1.8 NAME_1.7 KIND [OTHER_OLD_NAMES...]\n")
        f.write("# '-' means the particle does not exist in that range. KIND tells how extra data is sent.\n")
        f.write("\n".join(lines) + "\n")
    return len(lines)


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    xs_root = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "..", "core", "src", "main", "resources", "names")
    os.makedirs(out_dir, exist_ok=True)
    m = gen_materials(xs_root, os.path.join(out_dir, "materials.txt"))
    s = gen_sounds(xs_root, os.path.join(out_dir, "sounds.txt"))
    p = gen_particles(xs_root, os.path.join(out_dir, "particles.txt"))
    print("materials: %d, sounds: %d, particles: %d" % (m, s, p))


if __name__ == "__main__":
    main()
